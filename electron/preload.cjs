const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('dial', {
  pathForFile: (file) => webUtils.getPathForFile(file),
  chooseFiles: () => ipcRenderer.invoke('files:choose'),
  chooseFolderForFiles: () => ipcRenderer.invoke('folder:choose-for-files'),
  expandPaths: (paths) => ipcRenderer.invoke('files:expand-paths', paths),
  chooseFolder: () => ipcRenderer.invoke('folder:choose'),
  fileInfo: (filePath) => ipcRenderer.invoke('files:info', filePath),
  readFileBytes: (filePath) => ipcRenderer.invoke('files:read-bytes', filePath),
  mediaInfo: (filePath) => ipcRenderer.invoke('files:media-info', filePath),
  previewFrame: (filePath, timestamp) => ipcRenderer.invoke('files:preview-frame', { filePath, timestamp }),
  previewWaveform: (filePath, start, duration) => ipcRenderer.invoke('files:preview-waveform', { filePath, start, duration }),
  saveTextFile: (data) => ipcRenderer.invoke('files:save-text', data),
  exportResponsesXlsx: (responses) => ipcRenderer.invoke('responses:export-xlsx', responses),
  convert: (options) => ipcRenderer.invoke('convert:run', options),
  onProgress: (listener) => {
    const handler = (_event, payload) => listener(payload);
    ipcRenderer.on('convert:progress', handler);
    return () => ipcRenderer.removeListener('convert:progress', handler);
  },
  cancel: (jobId) => ipcRenderer.invoke('convert:cancel', jobId),
  openPath: (path) => ipcRenderer.invoke('path:open', path),
  revealPath: (path) => ipcRenderer.invoke('path:reveal', path),
  settingsGet: () => ipcRenderer.invoke('settings:get'),
  settingsSave: (settings) => ipcRenderer.invoke('settings:save', settings),
  updatesStatus: () => ipcRenderer.invoke('updates:status'),
  updatesCheck: () => ipcRenderer.invoke('updates:check'),
  updatesInstall: () => ipcRenderer.invoke('updates:install'),
  onUpdatesStatus: (listener) => { const handler = (_event, status) => listener(status); ipcRenderer.on('updates:status', handler); return () => ipcRenderer.removeListener('updates:status', handler); },
  formsList: () => ipcRenderer.invoke('forms:list'),
  formsSave: (form) => ipcRenderer.invoke('forms:save', form),
  formsDelete: (id) => ipcRenderer.invoke('forms:delete', id),
  responseSave: (response) => ipcRenderer.invoke('responses:save', response),
  responsesList: () => ipcRenderer.invoke('responses:list'),
  jobsList: () => ipcRenderer.invoke('jobs:list'),
  jobSave: (job) => ipcRenderer.invoke('jobs:save', job),
  jobDelete: (id) => ipcRenderer.invoke('jobs:delete', id),
  attachmentStore: (filePath, formId) => ipcRenderer.invoke('attachments:store', { filePath, formId }),
  syncStatus: () => ipcRenderer.invoke('sync:status'),
  syncNow: () => ipcRenderer.invoke('sync:now'),
  openExternal: (url) => ipcRenderer.invoke('external:open', url),
  appInfo: () => ipcRenderer.invoke('app:info'),
  quickClose: () => ipcRenderer.invoke('quick:close'),
  quickDropReceived: () => ipcRenderer.invoke('quick:drop-received'),
  quickOpen: () => ipcRenderer.invoke('quick:open'),
  quickState: () => ipcRenderer.invoke('quick:state'),
  quickShortcutStatus: () => ipcRenderer.invoke('quick:shortcut-status'),
  openFiles: (paths) => ipcRenderer.invoke('quick:open-files', paths),
  onFilesOpen: (listener) => { const handler = (_event, paths) => listener(paths); ipcRenderer.on('files:open', handler); return () => ipcRenderer.removeListener('files:open', handler); },
  onQuickOpen: (listener) => { const handler = (_event, paths) => listener(paths); ipcRenderer.on('quick:open', handler); return () => ipcRenderer.removeListener('quick:open', handler); },
  onQuickClose: (listener) => { const handler = () => listener(); ipcRenderer.on('quick:close', handler); return () => ipcRenderer.removeListener('quick:close', handler); },
});
